#!/usr/bin/env node
// Build the real Expo iOS application for the simulator, on a macOS runner.
//
// WHY THIS EXISTS
// Nothing else in this repository compiles the app that ships. The other job in
// .github/workflows/ios-tests.yml runs scripts/verify-native-tests.mjs, which does
// `xcodegen generate` + `xcodebuild` against the standalone project described by
// project.yml, and scripts/validate-mac.sh does the same. Both read VideoShrink/
// directly. Neither runs `expo prebuild` and neither runs `pod install`, so
// modules/videoshrink-native/ios/VideoShrinkNativeView.swift and
// VideoShrinkNativeModule.swift -- the Swift that makes this an Expo app -- are
// compiled by no gate at all. EAS does compile them, but EAS iOS build minutes are a
// rationed monthly resource on the free plan and were exhausted until 1 October 2026,
// so a mistake in those two files had no way to surface before then.
//
// The Expo pod's `source_files` in modules/videoshrink-native/ios/VideoShrinkNative.podspec
// is "**/*.{h,m,mm,swift,hpp,cpp}", so this build also compiles VideoShrinkCore/, the
// mirror of VideoShrink/{Models,Services,Presentation} that
// scripts/sync-native-sources.mjs generates. That is the same Swift an EAS build
// compiles, which makes a green run here the free, on-every-push equivalent of the
// compile half of an EAS build.
//
// WHAT IT DOES, IN ORDER
//   1. asserts the native-source mirror is present and in sync, by running the same
//      `node scripts/sync-native-sources.mjs --check` that EAS runs from
//      `eas-build-post-install`;
//   2. asserts ios/ does not exist -- it is generated by `expo prebuild` and is
//      git-ignored, so a clean checkout never has one -- then runs
//      `npx expo prebuild --platform ios --no-install` to generate it;
//   3. runs `pod install` in the generated ios/;
//   4. discovers the generated .xcworkspace and, from `xcodebuild -list -json` on it,
//      the scheme to build. Neither name is hardcoded: both are derived from
//      `expo.name` in app.json, and app.json is edited by other work;
//   5. runs the simulator build with CODE_SIGNING_ALLOWED=NO.
//
// WHAT IT IS NOT
// It does not run the tests (the verify-native-tests job does that), it does not
// deploy, publish or submit anything, and it needs no Apple account, no distribution
// certificate and no registered device: the destination is `generic/platform=iOS
// Simulator` and signing is off.
//
// PLATFORM
// This needs macOS, Xcode and CocoaPods and cannot run on the Windows machine this
// repository is normally edited on. On any non-macOS platform it prints a clear skip
// line and exits 0 -- unless CI is set, where a non-macOS runner means the job was
// pointed at the wrong image, which is a misconfiguration worth failing for rather
// than a silent green.
//
// `--check-only` runs only the parts that need no Xcode: the mirror check, a parse of
// app.json and the ios/ check. That is the path that can be exercised on Windows.
// `--replace-ios` removes a pre-existing generated ios/ instead of refusing to build.

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { delimiter, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BANNER = '===== VIDEOSHRINK EXPO APP BUILD =====';
const iosDirectory = resolve(root, 'ios');
const derivedDataPath = 'build/ExpoVerifyDerivedData';
const homebrewPaths = ['/opt/homebrew/bin', '/usr/local/bin'];

// Failures are thrown rather than exited on, and the process is ended by draining the
// event loop: process.exit() can truncate output still buffered on a pipe, and a CI
// log is a pipe.
class BuildFailure extends Error {
  constructor(message, exitCode) {
    super(message);
    // Always a real non-zero code. A BuildFailure that reached Node with an undefined
    // exitCode would end the process with status 0, which reads as a pass.
    this.exitCode = typeof exitCode === 'number' && exitCode !== 0 ? exitCode : 1;
  }
}

function banner(line) {
  console.log(`\n${line}\n`);
}

function fail(message, exitCode = 1) {
  throw new BuildFailure(message, exitCode);
}

// Child processes must see Homebrew's bin directory; its prefix differs between Intel
// (/usr/local) and Apple Silicon (/opt/homebrew) runners.
const inheritedPath = process.env.PATH ?? process.env.Path ?? '';
process.env.PATH = inheritedPath
  ? `${homebrewPaths.join(delimiter)}${delimiter}${inheritedPath}`
  : homebrewPaths.join(delimiter);

// Run a child process with its output streamed straight into the build log. A non-zero
// status is returned, never swallowed, so the caller can print the tool's own words and
// fail the build.
function run(command, args, step, cwd = root) {
  console.log(`[verify-expo-build] $ ${[command, ...args].join(' ')}`);
  const result = spawnSync(command, args, { cwd, env: process.env, stdio: 'inherit' });
  if (result.error) {
    fail(`${step} could not start: ${result.error.message}`);
  }
  return result.status ?? 1;
}

// Same child-process rules, but with the output captured instead of streamed, for the
// one command whose output has to be parsed. stderr is passed through: xcodebuild
// writes its warnings there and they are worth keeping in the log.
function runCaptured(command, args, step, cwd = root) {
  const result = spawnSync(command, args, { cwd, env: process.env, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  if (result.error) {
    fail(`${step} could not run: ${result.error.message}`);
  }
  if (result.status !== 0) {
    if (result.stderr) {
      process.stderr.write(result.stderr);
    }
    fail(`${step} exited with status ${result.status}. Its output is above.`, result.status);
  }
  if (result.stderr) {
    process.stderr.write(result.stderr);
  }
  return result.stdout ?? '';
}

function childEntryNames(directory) {
  try {
    return readdirSync(directory, { withFileTypes: true }).map(entry => entry.name);
  } catch {
    return [];
  }
}

// Step 1. The same assertion EAS makes from `eas-build-post-install`. `npm ci` runs the
// repo's postinstall, which regenerates the mirror, so in CI this confirms that the hook
// ran and the mirror matches VideoShrink/{Models,Services,Presentation} rather than
// proving the mirror was independently maintained. What it does catch is a checkout
// whose postinstall was skipped or removed, or a mirror left stale by a script edit --
// both of which would otherwise reach the compiler as surprising Swift.
function checkNativeSourceMirror() {
  const status = run(
    process.execPath,
    ['scripts/sync-native-sources.mjs', '--check'],
    'the native-source mirror check'
  );
  if (status !== 0) {
    fail(
      'the mirrored Swift under modules/videoshrink-native/ios/VideoShrinkCore/ is missing or stale. ' +
        'This is the same check EAS runs from eas-build-post-install, and it is the copy the Expo pod ' +
        'actually compiles, so the build below would compile something other than the sources in ' +
        'VideoShrink/. Run `npm run sync:native` and commit the sources that changed.',
      status
    );
  }
  console.log(
    '[verify-expo-build] The native-source mirror matches VideoShrink/{Models,Services,Presentation}.'
  );
}

// Step 2a. app.json is what `expo prebuild` reads to name the generated project, to pick
// the bundle identifier and to write the Photos usage strings. Reading it here turns an
// invalid file into a sentence rather than an Expo stack trace. It is read leniently: an
// Expo project may use app.config.js instead, in which case this only logs, and
// `expo prebuild` is left to have the final say.
function readAppConfig() {
  const path = resolve(root, 'app.json');
  if (!existsSync(path)) {
    console.log(
      '[verify-expo-build] app.json was not found; `expo prebuild` will decide whether the project ' +
        'uses app.config.js instead. Nothing is checked here.'
    );
    return;
  }

  let parsed;
  try {
    parsed = JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    fail(`app.json is not valid JSON, so \`expo prebuild\` cannot read it: ${error.message}`);
  }

  const expo = parsed && typeof parsed === 'object' ? parsed.expo : null;
  if (!expo || typeof expo !== 'object') {
    fail('app.json has no "expo" object, so `expo prebuild` cannot read the app configuration.');
  }
  if (typeof expo.name !== 'string' || expo.name.trim() === '') {
    fail(
      'app.json does not set "expo.name". Expo derives the generated Xcode project and scheme name ' +
        'from it, so `expo prebuild` would fail or generate an unnamed project.'
    );
  }
  const bundleIdentifier = expo.ios && typeof expo.ios === 'object' ? expo.ios.bundleIdentifier : null;
  if (typeof bundleIdentifier !== 'string' || bundleIdentifier.trim() === '') {
    fail('app.json does not set "expo.ios.bundleIdentifier", which `expo prebuild` requires.');
  }

  console.log(
    `[verify-expo-build] app.json parses: expo.name = "${expo.name}", expo.slug = "${
      typeof expo.slug === 'string' ? expo.slug : '(unset)'
    }", ios.bundleIdentifier = "${bundleIdentifier}".`
  );
  console.log(
    '[verify-expo-build] Expo names the generated Xcode project and its scheme after expo.name, so ' +
      'the expected project is "' +
      expo.name +
      '.xcodeproj". The scheme is still discovered from the generated workspace below rather than assumed.'
  );
}

// Step 2b. ios/ is generated by `expo prebuild` and is git-ignored (the `/ios/` rule in
// .gitignore), so a clean checkout never contains one. A pre-existing one would make
// prebuild sync into a stale tree and produce a confusing failure, so this refuses to
// continue unless the caller explicitly asks for it to be removed.
function ensureIosDirectoryIsAbsent(replaceExisting) {
  if (!existsSync(iosDirectory)) {
    console.log('[verify-expo-build] The generated ios/ directory does not exist yet, as it must not before `expo prebuild`.');
    return;
  }
  if (replaceExisting) {
    console.log(`[verify-expo-build] Removing the pre-existing generated directory ${iosDirectory} because --replace-ios was passed.`);
    rmSync(iosDirectory, { recursive: true, force: true });
    return;
  }
  fail(
    `${iosDirectory} already exists. That directory is generated by \`expo prebuild\` and is git-ignored, ` +
      'so a clean checkout never has one, and this step will not build on top of a stale generated tree. ' +
      'Remove it and run again, or pass --replace-ios to have this script remove it for you. On macOS: rm -rf ios'
  );
}

// Step 2c. Generate the native iOS project exactly the way EAS does.
function prebuildIosProject() {
  const status = run(
    'npx',
    ['expo', 'prebuild', '--platform', 'ios', '--no-install'],
    'npx expo prebuild --platform ios --no-install'
  );
  if (status !== 0) {
    fail('`npx expo prebuild --platform ios --no-install` failed. Its output is above.', status);
  }

  const podfile = resolve(iosDirectory, 'Podfile');
  if (!existsSync(podfile)) {
    fail(`expo prebuild finished but ${podfile} does not exist, so there is nothing for CocoaPods to install.`);
  }
  const projects = childEntryNames(iosDirectory).filter(name => name.endsWith('.xcodeproj'));
  if (projects.length === 0) {
    fail(`expo prebuild finished but generated no .xcodeproj inside ${iosDirectory}.`);
  }
  console.log(
    `[verify-expo-build] expo prebuild generated ${projects.join(', ')} with a Podfile. Its output above is the record of what it wrote.`
  );
}

// Step 3. CocoaPods turns the generated project into the workspace that actually builds.
function podInstall() {
  const status = run('pod', ['install'], 'pod install', iosDirectory);
  if (status !== 0) {
    fail(
      '`pod install` failed in the generated ios/ directory. Its output is above. A failure here is usually ' +
        'an environment or dependency problem rather than a Swift one, so read the first error in the output.',
      status
    );
  }
}

// Step 4a. `pod install` creates the workspace. Its name comes from `expo.name`, but it is
// discovered rather than assumed so that renaming the app in app.json does not silently
// break this gate.
function discoverWorkspace() {
  const entries = childEntryNames(iosDirectory);
  const workspaces = entries.filter(name => name.endsWith('.xcworkspace'));
  const projects = entries.filter(name => name.endsWith('.xcodeproj'));

  if (workspaces.length === 0) {
    fail(
      `\`pod install\` reported success but created no .xcworkspace inside ${iosDirectory}, so there is ` +
        `nothing to build. The directory contains: ${entries.join(', ') || '(nothing)'}.`
    );
  }
  if (workspaces.length === 1) {
    return resolve(iosDirectory, workspaces[0]);
  }

  // More than one workspace is unusual. Prefer the one named after the generated app
  // project, then any that is not a Pods workspace.
  const projectStems = projects.map(name => name.replace(/\.xcodeproj$/, ''));
  const namedAfterProject = projectStems.map(stem => `${stem}.xcworkspace`).find(name => workspaces.includes(name));
  const chosen = namedAfterProject ?? workspaces.find(name => !/^Pods[-.]/.test(name));
  if (!chosen) {
    fail(
      `${iosDirectory} contains more than one workspace (${workspaces.join(', ')}) and none is named after the ` +
        'generated app project, so this script cannot tell which one is the app.'
    );
  }
  console.log(
    `[verify-expo-build] ${iosDirectory} contains several workspaces (${workspaces.join(', ')}); using ${chosen}.`
  );
  return resolve(iosDirectory, chosen);
}

// `xcodebuild -list -json` prints a JSON object keyed by "workspace" (or "project") with a
// "schemes" array. Anything before the object is warning text, so the parse starts at the
// first brace.
function parseListing(text) {
  const start = text.indexOf('{');
  const end = text.lastIndexOf('}');
  if (start === -1 || end <= start) {
    return null;
  }
  try {
    return JSON.parse(text.slice(start, end + 1));
  } catch {
    return null;
  }
}

// Step 4b. Discover the scheme from the generated workspace. A wrong scheme is the single
// most likely way this job fails on its first run, which is why the name is read from the
// workspace instead of hardcoded from app.json.
function discoverScheme(workspacePath) {
  const workspaceArgument = relative(root, workspacePath);
  const stdout = runCaptured(
    'xcodebuild',
    ['-workspace', workspaceArgument, '-list', '-json'],
    'xcodebuild -list -json'
  );

  const listing = parseListing(stdout);
  const schemes =
    listing && listing.workspace && Array.isArray(listing.workspace.schemes)
      ? listing.workspace.schemes
      : listing && listing.project && Array.isArray(listing.project.schemes)
        ? listing.project.schemes
        : null;

  if (!schemes) {
    console.log('[verify-expo-build] xcodebuild -list -json did not print a readable scheme list. Its raw output was:');
    console.log(stdout);
    fail(
      `could not read the scheme list for ${workspaceArgument} from \`xcodebuild -list -json\`, so there is no ` +
        'safe way to choose a scheme. The raw output is above.'
    );
  }

  const candidates = schemes.filter(name => typeof name === 'string' && name.trim() !== '' && !/^Pods[-.]/.test(name));
  if (candidates.length === 0) {
    fail(
      `${workspaceArgument} lists no non-Pods scheme (it lists: ${schemes.join(', ') || '(none)'}), so there is ` +
        'nothing to build. This usually means `expo prebuild` did not generate the app target.'
    );
  }
  if (candidates.length === 1) {
    return candidates[0];
  }

  // More than one is unusual. Prefer the scheme named after the workspace, which is the
  // name Expo gives the app target.
  const workspaceStem = workspacePath.replace(/^.*[\\/]/, '').replace(/\.xcworkspace$/, '');
  const namedAfterWorkspace = candidates.find(name => name === workspaceStem);
  if (namedAfterWorkspace) {
    console.log(
      `[verify-expo-build] ${workspaceArgument} lists several buildable schemes (${candidates.join(', ')}); using ${namedAfterWorkspace}, the one named after the workspace.`
    );
    return namedAfterWorkspace;
  }
  fail(
    `${workspaceArgument} lists several non-Pods schemes (${candidates.join(', ')}) and none is named "${workspaceStem}", ` +
      'so this script cannot tell which one is the app. Add the intended name to this script rather than guessing.'
  );
}

// Step 5. Build the app for the simulator with signing off. No `-configuration` is passed,
// so the scheme's own default configuration is used, which is what the documented command
// in docs/VERIFICATION_HANDOFF.md specifies and what an EAS simulator build does.
function buildApp(workspacePath, scheme) {
  const status = run(
    'xcodebuild',
    [
      '-workspace',
      relative(root, workspacePath),
      '-scheme',
      scheme,
      '-sdk',
      'iphonesimulator',
      '-destination',
      'generic/platform=iOS Simulator',
      '-derivedDataPath',
      derivedDataPath,
      'CODE_SIGNING_ALLOWED=NO',
      'build'
    ],
    'xcodebuild build'
  );
  if (status !== 0) {
    fail(
      'the Expo app did not compile. The compiler output is directly above this line. This is the shipping ' +
        'target: it includes modules/videoshrink-native/ios/, which the standalone project in project.yml ' +
        'never compiles.',
      status
    );
  }
}

function preflight(replaceExistingIosDirectory) {
  checkNativeSourceMirror();
  readAppConfig();
  ensureIosDirectoryIsAbsent(replaceExistingIosDirectory);
}

function reportFailure(error) {
  banner(`${BANNER} FAILED`);
  if (error instanceof BuildFailure) {
    console.error(`[verify-expo-build] ${error.message}`);
    process.exitCode = error.exitCode;
  } else {
    console.error(error?.stack ?? String(error));
    process.exitCode = 1;
  }
}

const args = process.argv.slice(2);
const checkOnly = args.includes('--check-only');
const replaceIos = args.includes('--replace-ios');

if (checkOnly) {
  // The parts that need no Xcode and no macOS. This is the path that can be exercised on
  // the Windows machine the repository is normally edited on.
  banner(`${BANNER} CHECK ONLY`);
  try {
    // `--replace-ios` is honoured here too. It is an explicit request to remove the
    // generated directory, and ignoring it would make the remedy the failure message
    // prints untrue in this mode.
    preflight(replaceIos);
    banner(`${BANNER} CHECK ONLY PASSED`);
    console.log(
      '[verify-expo-build] Checked without Xcode: the native-source mirror is in sync, app.json parses, and ' +
        'the generated ios/ directory does not exist. Nothing here compiled anything, so this says nothing ' +
        'about whether the Swift builds. Run the script without --check-only on a Mac, or push to run the ' +
        'build-expo-app CI job, to compile the shipping target.'
    );
  } catch (error) {
    reportFailure(error);
  }
} else if (process.platform !== 'darwin') {
  const reason =
    `this step builds an iOS app with Xcode and CocoaPods, which requires macOS, but the platform is ${process.platform}`;
  if (process.env.CI) {
    reportFailure(
      new BuildFailure(
        `${reason}. CI is set, so this runner is not the macOS image the job asks for and this is a failure ` +
          'rather than a skip: a build gate that quietly passes on the wrong machine is worse than none.'
      )
    );
  } else {
    banner(`${BANNER} SKIPPED`);
    console.log(
      `[verify-expo-build] ${reason}. Run it on a Mac, or in CI on a macOS runner. \`--check-only\` performs the ` +
        'parts that need no Xcode.'
    );
  }
} else {
  banner(`${BANNER} START`);
  console.log(
    '[verify-expo-build] Building the shipping target: the Expo app, including ' +
      'modules/videoshrink-native/ios/, for the iOS Simulator with signing disabled.'
  );
  try {
    preflight(replaceIos);
    prebuildIosProject();
    podInstall();
    const workspace = discoverWorkspace();
    const scheme = discoverScheme(workspace);
    console.log(
      `[verify-expo-build] Using workspace ${relative(root, workspace)} and scheme ${scheme}. Both were ` +
        'discovered from what `pod install` and `xcodebuild -list -json` reported, not from a hardcoded name.'
    );
    buildApp(workspace, scheme);
    banner(`${BANNER} PASSED`);
    console.log(
      '[verify-expo-build] The Expo app compiled for the iOS Simulator. This proves the shipping target ' +
        'type-checks and compiles, including the Swift under modules/videoshrink-native/ios/ and the ' +
        'VideoShrinkCore/ mirror it embeds. It does not run the tests (the verify-native-tests job does ' +
        'that), it does not sign, deploy or submit anything, and it proves nothing about runtime ' +
        'behaviour on a device.'
    );
  } catch (error) {
    reportFailure(error);
  }
}
